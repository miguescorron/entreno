const BY_ID = new Map(EXERCISES.map((e) => [e.id, e]))

export function exerciseById(id: string): Exercise | undefined {
  return BY_ID.get(id)
}

export function videoUrl(e: Exercise): string {
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(e.video)}`
}

/** El ejercicio se puede hacer con el material disponible. */
export function canDo(e: Exercise, equipment: Equipment): boolean {
  if (equipment === 'gym') return true
  if (equipment === 'dumbbells') return e.equipment.some((x) => x === 'none' || x === 'dumbbells' || x === 'band')
  if (equipment === 'band') return e.equipment.some((x) => x === 'none' || x === 'band')
  return e.equipment.includes('none')
}

/** Si no se puede hacer, baja a la variante más fácil hasta encontrar una que sí. */
export function adaptToEquipment(id: string, equipment: Equipment): Exercise {
  let e = BY_ID.get(id)!
  const seen = new Set<string>()
  while (!canDo(e, equipment) && e.easier && !seen.has(e.id)) {
    seen.add(e.id)
    e = BY_ID.get(e.easier)!
  }
  return e
}
